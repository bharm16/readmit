// providerSwitch re-enters this test binary as the operator-declared program
// that prints a credential. A locator is an argument; a value never is.
const providerSwitch = "READMIT_TEST_ONLY_OBSERVE_PROVIDER"

func TestMain(m *testing.M) {
	if _, declared := os.LookupEnv(providerSwitch); declared {
		os.Exit(provider(os.Args[1:]))
	}
	os.Exit(m.Run())
}

func provider(arguments []string) int {
	if len(arguments) != 1 {
		return 4
	}
	data, err := os.ReadFile(arguments[0])
	if err != nil {
		return 5
	}
	if _, err := os.Stdout.Write(data); err != nil {
		return 6
	}
	return 0
}

// Every certificate and key below is generated by the test that uses them, for
// one test process, under a temporary directory it removes. None is committed,
// every listener is on loopback, on port 0, and closed by the test, and nothing
// here reaches a host outside this machine.
type authority struct {
	certificate *x509.Certificate
	key         *ecdsa.PrivateKey
	pem         []byte
}

func newAuthority(t *testing.T) *authority {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	template := &x509.Certificate{
		SerialNumber: serialNumber(t), Subject: pkix.Name{CommonName: "readmit test-only observation authority"},
		NotBefore: time.Now().Add(-time.Hour), NotAfter: time.Now().Add(time.Hour),
		KeyUsage: x509.KeyUsageCertSign | x509.KeyUsageDigitalSignature,
		IsCA:     true, BasicConstraintsValid: true,
	}
	der, err := x509.CreateCertificate(rand.Reader, template, template, key.Public(), key)
	if err != nil {
		t.Fatal(err)
	}
	signed, err := x509.ParseCertificate(der)
	if err != nil {
		t.Fatal(err)
	}
	return &authority{certificate: signed, key: key, pem: pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})}
}

// leaf signs one server certificate. The identity is explicit, so a test that
// needs a certificate naming the wrong host generates exactly that one.
func (a *authority) leaf(t *testing.T, addresses []net.IP, names []string) tls.Certificate {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	template := &x509.Certificate{
		SerialNumber: serialNumber(t), Subject: pkix.Name{CommonName: "readmit test-only observation endpoint"},
		NotBefore: time.Now().Add(-time.Hour), NotAfter: time.Now().Add(time.Hour),
		KeyUsage: x509.KeyUsageDigitalSignature, ExtKeyUsage: []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		IPAddresses: addresses, DNSNames: names,
	}
	der, err := x509.CreateCertificate(rand.Reader, template, a.certificate, key.Public(), a.key)
	if err != nil {
		t.Fatal(err)
	}
	encoded, err := x509.MarshalECPrivateKey(key)
	if err != nil {
		t.Fatal(err)
	}
	pair, err := tls.X509KeyPair(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}),
		pem.EncodeToMemory(&pem.Block{Type: "EC PRIVATE KEY", Bytes: encoded}))
	if err != nil {
		t.Fatal(err)
	}
	return pair
}

func serialNumber(t *testing.T) *big.Int {
	t.Helper()
	number, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 96))
	if err != nil {
		t.Fatal(err)
	}
	return number
}

// endpoint starts one loopback TLS listener on port 0 and closes it when the
// test ends. No listener outlives the test that started it.
func endpoint(t *testing.T, pair tls.Certificate, handler http.Handler) string {
	t.Helper()
	listener, err := tls.Listen("tcp", "127.0.0.1:0", &tls.Config{MinVersion: tls.VersionTLS12, Certificates: []tls.Certificate{pair}})
	if err != nil {
		t.Fatal(err)
	}
	server := &http.Server{Handler: handler, ReadHeaderTimeout: 5 * time.Second}
	done := make(chan struct{})
	go func() {
		defer close(done)
		_ = server.Serve(listener)
	}()
	t.Cleanup(func() {
		_ = server.Close()
		<-done
	})
	return listener.Addr().String()
}

