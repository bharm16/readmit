const appointmentBody = `{"appointments":[{"id":"A1"},{"id":"A2"}]}`

// declaredHTTP writes one source document beside the certificate authority it
// names and reads it back through the same public reader a command uses.
func declaredHTTP(t *testing.T, ca []byte, address, document string) (observesource.Source, string) {
	t.Helper()
	directory := t.TempDir()
	write(t, directory, "ca.pem", string(ca))
	document = strings.Replace(document, "ENDPOINT", "https://"+address+"/appointments", 1)
	path := write(t, directory, "source.json", document)
	source, err := observesource.ReadSource(path)
	if err != nil {
		t.Fatal(err)
	}
	return source, filepath.Join(t.TempDir(), "snapshot")
}

func loopback(t *testing.T, handler http.Handler) ([]byte, string) {
	t.Helper()
	ca := newAuthority(t)
	return ca.pem, endpoint(t, ca.leaf(t, []net.IP{net.ParseIP("127.0.0.1")}, nil), handler)
}

func answer(body string, prepare func(http.Header)) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		if prepare != nil {
			prepare(w.Header())
		}
		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write([]byte(body))
	})
}

func TestAnApprovedEndpointCompletesTheWindowOverTLS(t *testing.T) {
	ca, address := loopback(t, answer(appointmentBody, nil))
	source, snapshot := declaredHTTP(t, ca, address, declaredHTTPSource)
	completion := collect(t, source, window(t, declaredHTTPWindow), snapshot, "A1")
	if err := completion.Err(); err != nil {
		t.Fatalf("collection did not complete: %v", err)
	}
	if completion.RecordsObserved != 2 {
		t.Fatalf("records observed = %d, want 2", completion.RecordsObserved)
	}
	if err := completion.Correlated("A1"); err != nil {
		t.Fatalf("A1 was observed exactly once: %v", err)
	}
	// The destination decision is retained beside the material it governed.
	if _, err := os.Stat(filepath.Join(snapshot, "decision.json")); err != nil {
		t.Fatalf("the destination decision was not retained: %v", err)
	}
}

func TestAnHTTPReadThatFailedIsNeverAPassingAbsenceAssertion(t *testing.T) {
	for _, test := range []struct {
		name    string
		source  func(string) string
		handler http.Handler
		status  observewindow.Status
	}{
		{
			name:    "unauthorized",
			handler: http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) { w.WriteHeader(http.StatusUnauthorized) }),
			status:  observewindow.Failed,
		},
		{
			name:    "not found",
			handler: http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) { w.WriteHeader(http.StatusNotFound) }),
			status:  observewindow.Failed,
		},
		{
			name: "server error past every retry",
			source: func(document string) string {
				return strings.Replace(document, `"attempts": 0`, `"attempts": 2`, 1)
			},
			handler: http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) { w.WriteHeader(http.StatusServiceUnavailable) }),
			status:  observewindow.Failed,
		},
		{
			name: "redirection",
			handler: http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
				w.Header().Set("Location", "/elsewhere")
				w.WriteHeader(http.StatusFound)
			}),
			status: observewindow.Ambiguous,
		},
		{
			name: "response stating neither its age nor when it was generated",
			handler: http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
				w.Header()["Date"] = nil
				_, _ = w.Write([]byte(appointmentBody))
			}),
			status: observewindow.Ambiguous,
		},
		{
			name:    "cached response past the declared freshness bound",
			handler: answer(appointmentBody, func(header http.Header) { header.Set("Age", "7200") }),
			status:  observewindow.Stale,
		},
		{
			name: "response larger than the declared read bound",
			source: func(document string) string {
				return strings.Replace(document, `"max_bytes": 65536`, `"max_bytes": 8`, 1)
			},
			handler: answer(appointmentBody, nil),
			status:  observewindow.Truncated,
		},
		{
			name:    "response that is not the declared schema",
			handler: answer(`{"other":[{"id":"A1"}]}`, nil),
			status:  observewindow.Ambiguous,
		},
		{
			name:    "connection lost before the body arrived",
			handler: http.HandlerFunc(lostConnection),
			status:  observewindow.Failed,
		},
		{
			name: "read that ran out of its own time",
			source: func(document string) string {
				return strings.Replace(document, `"timeout": "3s"`, `"timeout": "50ms"`, 1)
			},
			handler: http.HandlerFunc(func(w http.ResponseWriter, request *http.Request) {
				select {
				case <-request.Context().Done():
				case <-time.After(3 * time.Second):
				}
			}),
			status: observewindow.Failed,
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			document := declaredHTTPSource
			if test.source != nil {
				document = test.source(document)
			}
			ca, address := loopback(t, test.handler)
			source, snapshot := declaredHTTP(t, ca, address, document)
			completion := collect(t, source, window(t, declaredHTTPWindow), snapshot)
			if completion.Status != test.status {
				t.Fatalf("status = %q, want %q", completion.Status, test.status)
			}
			if err := completion.AbsenceEvidence(); err == nil {
				t.Fatal("a failed read supported an absence assertion")
			}
			if completion.RecordsObserved != 0 {
				t.Fatal("a window that did not complete reported a settled count")
			}
			if completion.Status.RunState() != "execution_error" {
				t.Fatalf("run state = %q, want execution_error", completion.Status.RunState())
			}
		})
	}
}

// lostConnection promises more bytes than it sends and then drops the socket,
// which is what a read that lost its connection mid-body sees.
func lostConnection(w http.ResponseWriter, _ *http.Request) {
	hijacker, ok := w.(http.Hijacker)
	if !ok {
		return
	}
	connection, _, err := hijacker.Hijack()
	if err != nil {
		return
	}
	_, _ = connection.Write([]byte("HTTP/1.1 200 OK\r\nDate: " + time.Now().UTC().Format(http.TimeFormat) +
		"\r\nContent-Length: 400\r\n\r\n{\"appointments\":["))
	_ = connection.Close()
}

func TestARetryRecoversOnlyWhatProducedNoAnswerAtAll(t *testing.T) {
	var attempts atomic.Int64
	ca, address := loopback(t, http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		if attempts.Add(1) == 1 {
			w.WriteHeader(http.StatusServiceUnavailable)
			return
		}
		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write([]byte(appointmentBody))
	}))
	source, snapshot := declaredHTTP(t, ca, address, strings.Replace(declaredHTTPSource, `"attempts": 0`, `"attempts": 2`, 1))
	completion := collect(t, source, window(t, declaredHTTPWindow), snapshot)
	if err := completion.Err(); err != nil {
		t.Fatalf("a bounded retry of a read that produced no answer did not recover: %v", err)
	}
	// The retry is recorded rather than invisible: the first read's own record
	// states that it took two attempts.
	record, err := os.ReadFile(filepath.Join(snapshot, "read-0000", "read.json"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(record), `"attempts":2`) || !strings.Contains(string(record), `"retries":1`) {
		t.Fatalf("the retained read does not record its retries: %s", record)
	}
}

func TestARetryNeverTurnsAnUncertainReadIntoAConfidentOne(t *testing.T) {
	var attempts atomic.Int64
	ca, address := loopback(t, http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		// A stale answer first, then a fresh one. A collector that retried the
		// stale answer would report the source as current when it is not.
		if attempts.Add(1) == 1 {
			w.Header().Set("Age", "7200")
		}
		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write([]byte(appointmentBody))
	}))
	source, snapshot := declaredHTTP(t, ca, address, strings.Replace(declaredHTTPSource, `"attempts": 0`, `"attempts": 4`, 1))
	completion := collect(t, source, window(t, declaredHTTPWindow), snapshot)
	if completion.Status != observewindow.Stale {
		t.Fatalf("status = %q, want stale", completion.Status)
	}
	if attempts.Load() != 1 {
		t.Fatalf("the stale answer was read %d times; an answer is not retried", attempts.Load())
	}
}

